import esbuild from "esbuild";
import process from "node:process";
import { builtinModules } from "node:module";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Source: https://github.com/ (see repository README)
*/
`;

const production = process.argv[2] === "production";
// Profiling build for the limits harness (e2e/limits/profile.e2e.ts): production settings, but not minified, with an external
// source map, so CPU profiles show real function names. Never used for a release: `npm run build` does not set it.
const profiling = process.env.LOGWELL_PROFILE_BUILD === "1";

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
		...builtinModules.map((m) => `node:${m}`),
	],
	format: "cjs",
	target: "es2022",
	jsx: "automatic",
	jsxImportSource: "preact",
	logLevel: "info",
	sourcemap: profiling ? "external" : production ? false : "inline",
	treeShaking: true,
	minify: production && !profiling,
	outfile: "main.js",
});

if (production) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
